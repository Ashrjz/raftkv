const usage = `usage: kvcli [-addr host:port] <command> [flags]

commands:
  put [-file f | -size N] <key> [value]   value from arg, file, N generated bytes, or stdin
  get [-o file] <key>                     prints the value
  delete <key>
  snapshot
  selftest                                pass/fail checks against a live server
  bench [flags]                           load generator (bench -h)
  verify -ack-file FILE                   check every Put that bench acknowledged is present

exit codes: 0 ok, 1 not found, 2 failure`

func main() { os.Exit(run()) }

func run() int {
	addr := flag.String("addr", "localhost:7000", "server address")
	flag.Usage = func() { fmt.Fprintln(os.Stderr, usage) }
	flag.Parse()
	args := flag.Args()
	if len(args) == 0 {
		flag.Usage()
		return 2
	}
	cmds := map[string]func(*client.Client, []string) int{
		"put": cmdPut, "get": cmdGet, "delete": cmdDelete, "snapshot": cmdSnapshot,
		"selftest": cmdSelftest, "bench": cmdBench, "verify": cmdVerify,
	}
	fn, ok := cmds[args[0]]
	if !ok {
		flag.Usage()
		return 2
	}
	c, err := client.Dial(*addr, 0)
	if err != nil {
		return report(err)
	}
	defer c.Close()
	return fn(c, args[1:])
}

// report prints the gRPC code, which is what tells failure modes apart.
func report(err error) int {
	fmt.Fprintf(os.Stderr, "error: %s: %s\n", status.Code(err), status.Convert(err).Message())
	return 2
}

// codeOf is status.Code, except client.ErrNotFound (not a gRPC status) is NotFound.
func codeOf(err error) codes.Code {
	if errors.Is(err, client.ErrNotFound) {
		return codes.NotFound
	}
	return status.Code(err)
}

func callCtx() (context.Context, context.CancelFunc) {
	return context.WithTimeout(context.Background(), 30*time.Second)
}

func cmdPut(c *client.Client, args []string) int {
	fs := flag.NewFlagSet("put", flag.ExitOnError)
	file := fs.String("file", "", "read the value from this file")
	size := fs.Int("size", -1, "use a generated value of this many bytes")
	fs.Parse(args)
	if fs.NArg() < 1 {
		fmt.Fprintln(os.Stderr, "usage: put [-file f | -size N] <key> [value]")
		return 2
	}
	key := fs.Arg(0)
	var val []byte
	var err error
	switch {
	case *size >= 0:
		val = bytes.Repeat([]byte("x"), *size)
	case *file != "":
		val, err = os.ReadFile(*file)
	case fs.NArg() > 1:
		val = []byte(fs.Arg(1))
	default:
		val, err = io.ReadAll(os.Stdin)
	}
	if err != nil {
		return report(err)
	}
	ctx, cancel := callCtx()
	defer cancel()
	if err := c.Put(ctx, key, val); err != nil {
		return report(err)
	}
	fmt.Printf("OK (%d bytes)\n", len(val))
	return 0
}

func cmdGet(c *client.Client, args []string) int {
	fs := flag.NewFlagSet("get", flag.ExitOnError)
	out := fs.String("o", "", "write the value to this file instead of stdout")
	fs.Parse(args)
	if fs.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: get [-o file] <key>")
		return 2
	}
	ctx, cancel := callCtx()
	defer cancel()
	v, err := c.Get(ctx, fs.Arg(0))
	if errors.Is(err, client.ErrNotFound) {
		fmt.Fprintln(os.Stderr, "not found")
		return 1
	}
	if err != nil {
		return report(err)
	}
	if *out != "" {
		if err := os.WriteFile(*out, v, 0o644); err != nil {
			return report(err)
		}
		fmt.Printf("OK (%d bytes written to %s)\n", len(v), *out)
		return 0
	}
	fmt.Printf("%s\n", v)
	return 0
}

func cmdDelete(c *client.Client, args []string) int {
	if len(args) != 1 {
		fmt.Fprintln(os.Stderr, "usage: delete <key>")
		return 2
	}
	ctx, cancel := callCtx()
	defer cancel()
	if err := c.Delete(ctx, args[0]); err != nil {
		return report(err)
	}
	fmt.Println("OK")
	return 0
}

func cmdSnapshot(c *client.Client, _ []string) int {
	start := time.Now()
	if err := c.Snapshot(context.Background()); err != nil {
		return report(err)
	}
	fmt.Printf("OK (snapshot took %v)\n", time.Since(start).Round(time.Millisecond))
	return 0
}

// ---- selftest ----

func cmdSelftest(c *client.Client, _ []string) int {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	prefix := fmt.Sprintf("selftest-%d/", time.Now().UnixNano())
	passed, failed := 0, 0

	t := func(name string, f func() error) {
		if err := f(); err != nil {
			failed++
			fmt.Printf("FAIL  %s: %v\n", name, err)
			return
		}
		passed++
		fmt.Printf("PASS  %s\n", name)
	}
	wantCode := func(err error, want codes.Code) error {
		if got := status.Code(err); got != want {
			return fmt.Errorf("got %v (%v), want %v", got, err, want)
		}
		return nil
	}
	notFound := func(key string) error {
		if _, err := c.Get(ctx, key); !errors.Is(err, client.ErrNotFound) {
			return fmt.Errorf("got %v, want NotFound", err)
		}
		return nil
	}

	k := prefix + "k"
	t("put then get", func() error {
		if err := c.Put(ctx, k, []byte("v1")); err != nil {
			return err
		}
		return expectValue(ctx, c, k, []byte("v1"))
	})
	t("overwrite", func() error {
		if err := c.Put(ctx, k, []byte("v2")); err != nil {
			return err
		}
		return expectValue(ctx, c, k, []byte("v2"))
	})
	t("delete then get is NotFound", func() error {
		if err := c.Delete(ctx, k); err != nil {
			return err
		}
		return notFound(k)
	})
	t("delete again is idempotent", func() error { return c.Delete(ctx, k) })
	t("get of a never-written key is NotFound", func() error { return notFound(prefix + "never") })
	t("empty key is InvalidArgument", func() error {
		return wantCode(c.Put(ctx, "", []byte("v")), codes.InvalidArgument)
	})
	kMax := padKey(prefix, wal.MaxKeySize)
	t("key of MaxKeySize bytes is accepted", func() error {
		if err := c.Put(ctx, kMax, []byte("v")); err != nil {
			return err
		}
		if err := expectValue(ctx, c, kMax, []byte("v")); err != nil {
			return err
		}
		return c.Delete(ctx, kMax)
	})
	t("key of MaxKeySize+1 bytes is InvalidArgument", func() error {
		return wantCode(c.Put(ctx, padKey(prefix, wal.MaxKeySize+1), []byte("v")), codes.InvalidArgument)
	})
	t("empty value is accepted", func() error {
		ek := prefix + "empty"
		if err := c.Put(ctx, ek, nil); err != nil {
			return err
		}
		return expectValue(ctx, c, ek, nil)
	})
	t("value of MaxValueSize round-trips", func() error {
		bk, v := prefix+"big", pattern(wal.MaxValueSize)
		if err := c.Put(ctx, bk, v); err != nil {
			return err
		}
		if err := expectValue(ctx, c, bk, v); err != nil {
			return err
		}
		return c.Delete(ctx, bk)
	})
	t("value of MaxValueSize+1 is InvalidArgument", func() error {
		return wantCode(c.Put(ctx, prefix+"toobig", pattern(wal.MaxValueSize+1)), codes.InvalidArgument)
	})
	t("message above MaxMessageSize is ResourceExhausted", func() error {
		return wantCode(c.Put(ctx, prefix+"huge", pattern(server.MaxMessageSize+1)), codes.ResourceExhausted)
	})
	t("snapshot succeeds and data stays readable", func() error {
		sk := prefix + "snap"
		if err := c.Put(ctx, sk, []byte("before")); err != nil {
			return err
		}
		if err := c.Snapshot(ctx); err != nil {
			return err
		}
		return expectValue(ctx, c, sk, []byte("before"))
	})

	fmt.Printf("\n%d passed, %d failed\n", passed, failed)
	if failed > 0 {
		return 2
	}
	return 0
}

func expectValue(ctx context.Context, c *client.Client, key string, want []byte) error {
	got, err := c.Get(ctx, key)
	if err != nil {
		return err
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("value mismatch (got %d bytes, want %d)", len(got), len(want))
	}
	return nil
}

// padKey returns prefix padded with 'k' to exactly n bytes.
func padKey(prefix string, n int) string { return prefix + strings.Repeat("k", n-len(prefix)) }

func pattern(n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(i % 251)
	}
	return b
}

// ---- bench ----

type result struct {
	op   string // "put" or "get"
	lat  time.Duration
	code codes.Code
}

// valueFor derives a value from the key, so verify can recompute it.
func valueFor(key string, size int) []byte {
	return bytes.Repeat([]byte(key), size/len(key)+1)[:size]
}

func cmdBench(c *client.Client, args []string) int {
	fs := flag.NewFlagSet("bench", flag.ExitOnError)
	workers := fs.Int("workers", 16, "concurrent workers")
	rate := fs.Int("rate", 0, "fixed total requests/s; latency is measured from each request's scheduled time (0 = closed loop, as fast as possible)")
	dur := fs.Duration("duration", 10*time.Second, "how long to generate load")
	vsize := fs.Int("value-size", 128, "value size in bytes")
	readPct := fs.Int("read-pct", 0, "percentage of operations that are Gets (0-100)")
	timeout := fs.Duration("timeout", 3*time.Second, "per-request timeout")
	p99 := fs.Duration("p99", 0, "exit 2 if the put or get p99 exceeds this (0 = just report)")
	allowUnavail := fs.Bool("allow-unavailable", false, "treat Unavailable as a clean rejection, not a failure (crash and shutdown tests)")
	ackFile := fs.String("ack-file", "", "append every acknowledged Put to this file as 'key size'")
	fs.Parse(args)

	var af *os.File
	var ackMu sync.Mutex
	if *ackFile != "" {
		var err error
		if af, err = os.OpenFile(*ackFile, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o644); err != nil {
			return report(err)
		}
		defer af.Close()
	}
	ack := func(key string) {
		if af == nil {
			return
		}
		ackMu.Lock()
		fmt.Fprintf(af, "%s %d\n", key, *vsize) // unbuffered: survives the bench being killed
		ackMu.Unlock()
	}

	runID := fmt.Sprintf("bench-%d", time.Now().UnixNano())
	start := time.Now()
	deadline := start.Add(*dur)

	// Fixed rate: a generator hands out scheduled send times. Latency counts from
	// the scheduled time, so a backlog shows up as latency instead of being hidden.
	jobs := make(chan time.Time, 1024)
	if *rate > 0 {
		go func() {
			defer close(jobs)
			interval := time.Second / time.Duration(*rate)
			for i := 0; ; i++ {
				at := start.Add(time.Duration(i) * interval)
				if at.After(deadline) {
					return
				}
				time.Sleep(time.Until(at))
				jobs <- at
			}
		}()
	}
	next := func() (time.Time, bool) {
		if *rate > 0 {
			t, ok := <-jobs
			return t, ok
		}
		if time.Now().After(deadline) {
			return time.Time{}, false
		}
		return time.Now(), true
	}

	results := make([][]result, *workers)
	var wg sync.WaitGroup
	for w := 0; w < *workers; w++ {
		wg.Add(1)
		go func(w int) {
			defer wg.Done()
			rng := rand.New(rand.NewSource(time.Now().UnixNano() + int64(w)))
			var written []string
			n := 0
			for {
				t0, ok := next()
				if !ok {
					return
				}
				ctx, cancel := context.WithTimeout(context.Background(), *timeout)
				var r result
				if len(written) > 0 && rng.Intn(100) < *readPct {
					_, err := c.Get(ctx, written[rng.Intn(len(written))])
					r = result{"get", time.Since(t0), codeOf(err)}
				} else {
					key := fmt.Sprintf("%s-w%d-%d", runID, w, n)
					n++
					err := c.Put(ctx, key, valueFor(key, *vsize))
					r = result{"put", time.Since(t0), codeOf(err)}
					if err == nil {
						written = append(written, key)
						ack(key)
					}
				}
				cancel()
				results[w] = append(results[w], r)
				if r.code == codes.Unavailable {
					time.Sleep(5 * time.Millisecond) // server is down: don't spin
				}
			}
		}(w)
	}
	wg.Wait()
	elapsed := time.Since(start)

	byOp := map[string][]time.Duration{}
	counts := map[codes.Code]int{}
	total := 0
	for _, rs := range results {
		for _, r := range rs {
			total++
			counts[r.code]++
			if r.code == codes.OK {
				byOp[r.op] = append(byOp[r.op], r.lat)
			}
		}
	}
	fmt.Printf("%d requests in %v (%.0f req/s)\n", total, elapsed.Round(time.Millisecond), float64(total)/elapsed.Seconds())
	var worst time.Duration
	for _, op := range []string{"put", "get"} {
		l := byOp[op]
		if len(l) == 0 {
			continue
		}
		sort.Slice(l, func(i, j int) bool { return l[i] < l[j] })
		p := pct(l, 99)
		fmt.Printf("%-4s ok=%d  p50=%v  p99=%v  max=%v\n", op, len(l), pct(l, 50), p, l[len(l)-1])
		if p > worst {
			worst = p
		}
	}
	var cs []codes.Code
	for code := range counts {
		cs = append(cs, code)
	}
	sort.Slice(cs, func(i, j int) bool { return cs[i] < cs[j] })
	fmt.Println("status codes:")
	bad := 0
	for _, code := range cs {
		fmt.Printf("  %-18v %d\n", code, counts[code])
		if code != codes.OK && !(code == codes.Unavailable && *allowUnavail) {
			bad += counts[code]
		}
	}

	exit := 0
	if bad > 0 {
		fmt.Printf("FAIL: %d requests ended with an unexpected status\n", bad)
		exit = 2
	}
	if *p99 > 0 && worst > *p99 {
		fmt.Printf("FAIL: p99 %v exceeds target %v\n", worst, *p99)
		exit = 2
	}
	return exit
}

func pct(sorted []time.Duration, p int) time.Duration {
	i := len(sorted) * p / 100
	if i >= len(sorted) {
		i = len(sorted) - 1
	}
	return sorted[i]
}

// ---- verify ----

func cmdVerify(c *client.Client, args []string) int {
	fs := flag.NewFlagSet("verify", flag.ExitOnError)
	ackFile := fs.String("ack-file", "", "file written by bench -ack-file (required)")
	fs.Parse(args)
	if *ackFile == "" {
		fmt.Fprintln(os.Stderr, "usage: verify -ack-file FILE")
		return 2
	}
	f, err := os.Open(*ackFile)
	if err != nil {
		return report(err)
	}
	defer f.Close()

	type entry struct {
		key  string
		size int
	}
	var entries []entry
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		var e entry
		if _, err := fmt.Sscanf(sc.Text(), "%s %d", &e.key, &e.size); err == nil {
			entries = append(entries, e) // a torn last line is skipped
		}
	}
	if len(entries) == 0 {
		fmt.Println("FAIL: no acknowledged writes in the file; nothing to verify")
		return 2
	}

	var mu sync.Mutex
	missing, mismatch, other := 0, 0, 0
	var samples []string
	work := make(chan entry)
	var wg sync.WaitGroup
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for e := range work {
				ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
				v, err := c.Get(ctx, e.key)
				cancel()
				mu.Lock()
				switch {
				case errors.Is(err, client.ErrNotFound):
					missing++
				case err != nil:
					other++
				case !bytes.Equal(v, valueFor(e.key, e.size)):
					mismatch++
				default:
					mu.Unlock()
					continue
				}
				if len(samples) < 5 {
					samples = append(samples, e.key)
				}
				mu.Unlock()
			}
		}()
	}
	for _, e := range entries {
		work <- e
	}
	close(work)
	wg.Wait()

	fmt.Printf("verified %d acknowledged writes: missing=%d mismatch=%d errors=%d\n",
		len(entries), missing, mismatch, other)
	if missing+mismatch+other > 0 {
		fmt.Printf("FAIL: first bad keys: %v\n", samples)
		return 2
	}
	return 0
}
